// Pure TypeScript types for the scheduling engine.
// No Prisma imports. No runtime logic.

// ─── Enums (string unions, not Prisma enums) ─────────────────────────────────

export type ShiftType = "MORNING" | "EVENING" | "NIGHT";

export type DayCategory = "WEEKDAY" | "FRIDAY" | "SATURDAY" | "HOLIDAY";

export type WarningType =
  | "MIN_NOT_MET"
  | "UNFILLED"
  | "UNDERSTAFFED"
  | "CONFLICT"
  | "FAIRNESS";

export type WarningSeverity = "ERROR" | "WARNING" | "INFO";

export type OverflowCandidateReason = "CAPACITY_FULL" | "LOWER_SCORE";

// ─── Input types ─────────────────────────────────────────────────────────────

export interface EngineEmployee {
  rank: number;
  id: string;
  positionId: string;
  positionName?: string;
  facilityId: string;
  isActive: boolean;
}

export interface EngineCapacity {
  requiredRank: number;
  positionId: string;
  positionName?: string;
  shiftType: ShiftType;
  dayCategory: DayCategory;
  amount: number;
}

export interface EngineAssignment {
  employeeId: string;
  facilityId: string;
  positionId: string;
  positionName?: string;
  date: Date;
  shiftType: ShiftType;
  slotIndex: number;
  isManualOverride: boolean;
  /** Persisted origin: manager edits may override submitted availability. */
  source?: 'MANUAL' | 'AUTOMATIC';
}

export interface EngineInput {
  historicalAssignments?: EngineAssignment[];
  boundaryAssignments?: EngineAssignment[];
  preferences?: Map<string, Set<string>>;
  holidayCategories?: Map<string, DayCategory>;
  period: {
    id: string;
    facilityId: string;
    startDate: Date;
    endDate: Date;
  };
  // Week 1 = first 7 dates of the period; Week 2 = last 7 dates.
  week1Dates: Date[];
  week2Dates: Date[];
  employees: EngineEmployee[];
  // employeeId → Set of "YYYY-MM-DD|MORNING" | "YYYY-MM-DD|EVENING" | "YYYY-MM-DD|NIGHT"
  availability: Map<string, Set<string>>;
  capacities: EngineCapacity[];
  // Explicitly locked assignments; provenance is stored separately by the application.
  manualAssignments: EngineAssignment[];
  scheduleId: string;
}

// ─── Engine working types ─────────────────────────────────────────────────────

export interface EngineSlot {
  requiredRank: number;
  facilityId: string;
  positionId: string;
  positionName?: string;
  date: Date;
  shiftType: ShiftType;
  dayCategory: DayCategory;
  // Total number of employees required for this slot.
  requiredAmount: number;
}

// ─── Output types ─────────────────────────────────────────────────────────────

export interface EngineWarning {
  type: WarningType;
  severity: WarningSeverity;
  message: string;
  employeeId?: string;
  positionId?: string;
  date?: Date;
  shiftType?: ShiftType;
}

export interface UnmetMinimum {
  employeeId: string;
  // 1 or 2
  weekNumber: 1 | 2;
  shiftType: "MORNING" | "EVENING";
  required: number;
  actual: number;
}

export interface OverflowCandidate {
  employeeId: string;
  facilityId: string;
  positionId: string;
  date: Date;
  shiftType: ShiftType;
  reason: OverflowCandidateReason;
}

export interface FairnessSummary {
  employeeId: string;
  totalShifts: number;
  morningShifts: number;
  eveningShifts: number;
  nightShifts: number;
  weekendShifts: number;
}

export interface EngineStats {
  totalSlots: number;
  filledSlots: number;
  unfilledSlots: number;
  totalAssignments: number;
  employeesWithUnmetMinimums: number;
  durationMs: number;
}

export interface EngineOutput {
  // New assignments generated by the engine (excludes manual assignments).
  assignments: EngineAssignment[];
  // Slots that could not be filled at all (0 assigned, amount > 0).
  unfilledSlots: EngineSlot[];
  // Employees who did not receive their required weekly minimum shifts.
  unmetMinimums: UnmetMinimum[];
  // All generated warnings (MIN_NOT_MET, UNFILLED, UNDERSTAFFED, FAIRNESS).
  warnings: EngineWarning[];
  // Employees who were eligible for a slot but not assigned (informational only).
  overflowCandidates: OverflowCandidate[];
  // Per-employee shift counts across all assignments (manual + generated).
  fairnessSummary: Map<string, FairnessSummary>;
  stats: EngineStats;
}
